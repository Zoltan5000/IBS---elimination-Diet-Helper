// Generates 9-slice pixel-corner frames (NES-style border-image) as CSS custom properties.
// 7x7 grid, 3-pixel corners, 1-pixel line. Each SVG pixel is drawn at 2 CSS px (border-width 6px).
const grid = [
  '..XXX..',
  '.XfffX.',
  'XfffffX',
  'XfffffX',
  'XfffffX',
  '.XfffX.',
  '..XXX..',
];
function svg(fill, line) {
  let r = '';
  // One path per colour, merging runs of pixels in each row to keep the data URI small
  const path = ch => grid.map((row, y) => {
    let d = '';
    row.replace(new RegExp(ch + '+', 'g'), (m, x) => { d += `M${x} ${y}h${m.length}v1h-${m.length}z`; return m; });
    return d;
  }).join('');
  r = `<path fill='${line}' d='${path('X')}'/><path fill='${fill}' d='${path('f')}'/>`;
  const s = `<svg xmlns='http://www.w3.org/2000/svg' width='7' height='7' shape-rendering='crispEdges'>${r}</svg>`;
  return `url("data:image/svg+xml,${s.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
}
